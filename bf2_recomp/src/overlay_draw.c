void overlay_font_build_atlas(uint8_t *atlas_out, uint32_t width, uint32_t height)
{
    if (!atlas_out || width < ATLAS_W || height < ATLAS_H) return;
    memset(atlas_out, 0, width * height);

    /* Slot 0 is reserved for solid white 4x4 block at (0, 0) */
    for (int y = 0; y < 4; y++) {
        for (int x = 0; x < 4; x++) {
            atlas_out[y * width + x] = 255;
        }
    }

    /* Place glyphs starting at slot 1 */
    for (int i = 0; i < OVERLAY_FONT_CHAR_COUNT; i++) {
        int slot = i + 1;
        int sx = (slot % CHARS_PER_ROW) * OVERLAY_FONT_CHAR_W;
        int sy = (slot / CHARS_PER_ROW) * OVERLAY_FONT_CHAR_H;

        for (int row = 0; row < OVERLAY_FONT_CHAR_H; row++) {
            uint8_t b = g_overlay_font_8x12[i][row];
            for (int col = 0; col < OVERLAY_FONT_CHAR_W; col++) {
                if (b & (0x80 >> col)) {
                    atlas_out[(sy + row) * width + (sx + col)] = 255;
                }
            }
        }
    }
}

void overlay_batch_init(OverlayBatch *batch, uint32_t initial_quads)
{
    if (!batch) return;
    if (initial_quads == 0) initial_quads = 64;
    batch->count = 0;
    batch->capacity = initial_quads * 6;
    batch->vertices = (OverlayVertex *)malloc(batch->capacity * sizeof(OverlayVertex));
}

void overlay_batch_clear(OverlayBatch *batch)
{
    if (!batch) return;
    batch->count = 0;
}

void overlay_batch_free(OverlayBatch *batch)
{
    if (!batch) return;
    if (batch->vertices) {
        free(batch->vertices);
        batch->vertices = NULL;
    }
    batch->count = 0;
    batch->capacity = 0;
}

void overlay_batch_reserve(OverlayBatch *batch, uint32_t additional_quads)
{
    if (!batch) return;
    uint32_t needed = batch->count + additional_quads * 6;
    if (needed > batch->capacity) {
        uint32_t new_cap = batch->capacity ? batch->capacity * 2 : 256;
        while (new_cap < needed) new_cap *= 2;
        batch->vertices = (OverlayVertex *)realloc(batch->vertices, new_cap * sizeof(OverlayVertex));
        batch->capacity = new_cap;
    }
}

static inline void emit_quad(OverlayBatch *batch,
                             float x0, float y0, float x1, float y1,
                             float u0, float v0, float u1, float v1,
                             uint32_t color)
{
    overlay_batch_reserve(batch, 1);
    OverlayVertex *v = &batch->vertices[batch->count];

    /* Triangle 1: (x0, y0), (x1, y0), (x0, y1) */
    v[0].x = x0; v[0].y = y0; v[0].u = u0; v[0].v = v0; v[0].color = color;
    v[1].x = x1; v[1].y = y0; v[1].u = u1; v[1].v = v0; v[1].color = color;
    v[2].x = x0; v[2].y = y1; v[2].u = u0; v[2].v = v1; v[2].color = color;

    /* Triangle 2: (x1, y0), (x1, y1), (x0, y1) */
    v[3].x = x1; v[3].y = y0; v[3].u = u1; v[3].v = v0; v[3].color = color;
    v[4].x = x1; v[4].y = y1; v[4].u = u1; v[4].v = v1; v[4].color = color;
    v[5].x = x0; v[5].y = y1; v[5].u = u0; v[5].v = v1; v[5].color = color;

    batch->count += 6;
}

void overlay_draw_rect(OverlayBatch *batch, float x, float y, float w, float h, uint32_t color)
{
    /* Solid white pixel is at center of (1, 1) */
    float u = 1.0f / (float)ATLAS_W;
    float v = 1.0f / (float)ATLAS_H;
    emit_quad(batch, x, y, x + w, y + h, u, v, u, v, color);
}

void overlay_draw_rect_outline(OverlayBatch *batch, float x, float y, float w, float h, float thickness, uint32_t color)
{
    /* Top, Bottom, Left, Right borders */
    overlay_draw_rect(batch, x, y, w, thickness, color);
    overlay_draw_rect(batch, x, y + h - thickness, w, thickness, color);
    overlay_draw_rect(batch, x, y + thickness, thickness, h - 2.0f * thickness, color);
    overlay_draw_rect(batch, x + w - thickness, y + thickness, thickness, h - 2.0f * thickness, color);
}

void overlay_draw_text(OverlayBatch *batch, float x, float y, float scale, const char *text, uint32_t color)
{
    if (!batch || !text) return;
    float cur_x = x;
    float cur_y = y;
    float cw = (float)OVERLAY_FONT_CHAR_W * scale;
    float ch = (float)OVERLAY_FONT_CHAR_H * scale;

    while (*text) {
        char c = *text++;
        if (c == '\n') {
            cur_x = x;
            cur_y += ch + 2.0f * scale;
            continue;
        }
        if (c < OVERLAY_FONT_FIRST_CHAR || c > OVERLAY_FONT_LAST_CHAR) {
            cur_x += cw;
            continue;
        }
        if (c == ' ') {
            cur_x += cw;
            continue;
        }

        int slot = (c - OVERLAY_FONT_FIRST_CHAR) + 1;
        int sx = (slot % CHARS_PER_ROW) * OVERLAY_FONT_CHAR_W;
        int sy = (slot / CHARS_PER_ROW) * OVERLAY_FONT_CHAR_H;

        float u0 = (float)sx / (float)ATLAS_W;
        float v0 = (float)sy / (float)ATLAS_H;
        float u1 = (float)(sx + OVERLAY_FONT_CHAR_W) / (float)ATLAS_W;
        float v1 = (float)(sy + OVERLAY_FONT_CHAR_H) / (float)ATLAS_H;

        emit_quad(batch, cur_x, cur_y, cur_x + cw, cur_y + ch, u0, v0, u1, v1, color);
        cur_x += cw;
    }
}
